-- V1: initial schema for the expense claim application.
-- Flyway runs this file once and records it in the flyway_schema_history table.
-- Never edit this file after it has been applied; add a new V2__... file instead.

CREATE TABLE departments (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    CONSTRAINT uk_departments_name UNIQUE (name)
);

CREATE TABLE employees (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(150) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    department_id BIGINT       NOT NULL,
    CONSTRAINT uk_employees_email UNIQUE (email),
    CONSTRAINT fk_employees_department FOREIGN KEY (department_id) REFERENCES departments (id),
    CONSTRAINT ck_employees_role CHECK (role IN ('EMPLOYEE', 'MANAGER', 'FINANCE'))
);

CREATE TABLE expense_claims (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id  BIGINT        NOT NULL,
    category     VARCHAR(30)   NOT NULL,
    amount       NUMERIC(12, 2) NOT NULL,
    expense_date DATE          NOT NULL,
    description  VARCHAR(500),
    status       VARCHAR(20)   NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    -- Used by JPA optimistic locking (@Version) to detect concurrent updates.
    version      BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT fk_expense_claims_employee FOREIGN KEY (employee_id) REFERENCES employees (id),
    -- Database-level safety net; the API will also validate this in Checkpoint 2.
    CONSTRAINT ck_expense_claims_amount_positive CHECK (amount > 0),
    CONSTRAINT ck_expense_claims_category CHECK (category IN
        ('TRAVEL', 'MEALS', 'ACCOMMODATION', 'OFFICE_SUPPLIES', 'TRAINING', 'OTHER')),
    CONSTRAINT ck_expense_claims_status CHECK (status IN
        ('SUBMITTED', 'APPROVED', 'REJECTED'))
);

CREATE TABLE approval_comments (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id     BIGINT        NOT NULL,
    author_id    BIGINT        NOT NULL,
    action       VARCHAR(20)   NOT NULL,
    comment_text VARCHAR(1000),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_approval_comments_claim FOREIGN KEY (claim_id) REFERENCES expense_claims (id),
    CONSTRAINT fk_approval_comments_author FOREIGN KEY (author_id) REFERENCES employees (id),
    CONSTRAINT ck_approval_comments_action CHECK (action IN ('COMMENT', 'APPROVE', 'REJECT'))
);

-- PostgreSQL does not create indexes for foreign keys automatically.
-- These indexes match the queries planned for later checkpoints.

-- Department pending approvals: join employees by department.
CREATE INDEX idx_employees_department_id ON employees (department_id);

-- "My claims" lookups by owner.
CREATE INDEX idx_expense_claims_employee_id ON expense_claims (employee_id);

-- Pending-approval queries filter by status and join to the owning employee.
CREATE INDEX idx_expense_claims_status_employee_id ON expense_claims (status, employee_id);

-- Date-range filters and the monthly category report.
CREATE INDEX idx_expense_claims_expense_date ON expense_claims (expense_date);

-- Loading all comments for one claim.
CREATE INDEX idx_approval_comments_claim_id ON approval_comments (claim_id);
